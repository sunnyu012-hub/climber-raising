/** 닉네임 규칙 — UI와 검증이 같은 값을 쓴다. */
export const NICKNAME_RULE = { min: 2, max: 10 } as const

export function isValidNickname(raw: string): boolean {
  const v = raw.trim()
  return v.length >= NICKNAME_RULE.min && v.length <= NICKNAME_RULE.max
}
